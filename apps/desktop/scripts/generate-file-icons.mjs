#!/usr/bin/env node
/**
 * The file tree's icon subset, generated.
 *
 * Material Icon Theme (MIT) ships 1,251 glyphs and 3,500-odd mappings. This takes the allowlist
 * in `file-icons.allow.txt`, prunes Material's own table to the entries whose icon is on it, and
 * emits **one checked-in TypeScript module** of inlined greyed paths — the shape Drizzle's
 * checked-in migrations already use, and the only place in the app allowed to hold these paths,
 * exactly as `RuntimeMark.tsx` is for a runtime's vendor mark.
 *
 * **Greyed, and greyed loses nothing.** Across all of Material's extension and filename
 * mappings, zero pairs become indistinguishable when the fill becomes `currentColor`: colour is
 * a property of a glyph here and never what separates two of them
 * (`.scratch/file-sidebar/issues/07`). So every fill, stroke and gradient is stripped and the
 * component paints one `currentColor`.
 *
 * **Bundled, never fetched.** `material-icon-theme` is a devDependency; nothing ships it and
 * nothing reaches a CDN at runtime, which is the local-first rule.
 *
 * Excluded on purpose: Material's ~250 named folder icons, because ticket 01 said *a* folder
 * glyph, and the `_light` duplicates, which greyed are duplicates of nothing.
 *
 *   node scripts/generate-file-icons.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const themeRoot = dirname(dirname(require.resolve('material-icon-theme/dist/material-icons.json')));
const theme = JSON.parse(readFileSync(join(themeRoot, 'dist', 'material-icons.json'), 'utf8'));
const version = JSON.parse(readFileSync(join(themeRoot, 'package.json'), 'utf8')).version;

const allowed = readFileSync(join(here, 'file-icons.allow.txt'), 'utf8')
  .split('\n')
  .map((line) => line.trim())
  .filter((line) => line !== '' && !line.startsWith('#'));

/** Everything that carries a colour, and everything that could smuggle one back in. */
const COLOUR = /\s(fill|stroke|style|class|opacity|fill-opacity|stroke-opacity|stop-color)="[^"]*"/g;
const DEFS = /<(defs|linearGradient|radialGradient|style|clipPath)\b[\s\S]*?<\/\1>/g;

function glyph(name) {
  const svg = readFileSync(join(themeRoot, 'icons', `${name}.svg`), 'utf8');
  const box = /viewBox="([^"]+)"/.exec(svg)?.[1];
  if (box === undefined) throw new Error(`${name}.svg has no viewBox`);
  const body = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(DEFS, '')
    .replace(COLOUR, '')
    .replace(/\s{2,}/g, ' ')
    .trim();
  // A glyph that still points at something we removed would draw as nothing at all, silently.
  // Better to refuse it here than to ship a blank row.
  if (/url\(#|<use\b|<image\b/.test(body)) {
    throw new Error(`${name}.svg needs a definition greying removed; leave it off the allowlist`);
  }
  return { box, body };
}

const glyphs = {};
for (const name of allowed) glyphs[name] = glyph(name);

/** Material's own table, pruned to what is bundled. Never retyped, and never a folder name. */
const prune = (table) =>
  Object.fromEntries(
    Object.entries(table)
      .filter(([key, icon]) => glyphs[icon] !== undefined && !key.endsWith('_light'))
      .sort(([left], [right]) => left.localeCompare(right)),
  );

const byExtension = prune(theme.fileExtensions);
const byName = prune(theme.fileNames);

const literal = (value) => JSON.stringify(value, null, 2).replace(/\n/g, '\n');

const module = `// GENERATED by scripts/generate-file-icons.mjs from material-icon-theme@${version} (MIT).
// Do not edit. Widen it by adding a name to scripts/file-icons.allow.txt and running the
// generator again.
//
// Material Icon Theme is MIT licensed. Its notice ships beside this file as LICENSE.material.
//
// The one module in the app allowed to hold these paths, which is the second and last exception
// to DESIGN.md's Icons rule: greyed to one \`currentColor\`, never coloured, never in place of
// the name. It stops at the file tree.

export interface FileGlyph {
  readonly box: string;
  readonly body: string;
}

/** ${allowed.length} glyphs, every fill and gradient stripped. */
export const FILE_GLYPHS: Record<string, FileGlyph> = ${literal(glyphs)};

/** ${Object.keys(byExtension).length} of Material's extension mappings, pruned to what is bundled. */
export const BY_EXTENSION: Record<string, string> = ${literal(byExtension)};

/** ${Object.keys(byName).length} of Material's whole-filename mappings, pruned the same way. */
export const BY_FILENAME: Record<string, string> = ${literal(byName)};

/** What an extension nobody bundled draws. A miss is this set's resting state, not a failure. */
export const GENERIC = ${JSON.stringify(theme.file)};
export const FOLDER = ${JSON.stringify(theme.folder)};
export const FOLDER_OPEN = ${JSON.stringify(theme.folderExpanded)};
`;

const out = join(here, '..', 'src', 'renderer', 'src', 'components', 'file-icons.generated.ts');
writeFileSync(out, module);
writeFileSync(
  join(here, '..', 'src', 'renderer', 'src', 'components', 'LICENSE.material'),
  readFileSync(join(themeRoot, 'LICENSE'), 'utf8'),
);
process.stdout.write(
  `${allowed.length} glyphs, ${Object.keys(byExtension).length} extensions, ${Object.keys(byName).length} filenames -> ${out}\n`,
);
